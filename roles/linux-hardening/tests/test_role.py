    def test_moduli_keeps_2048_bit_groups_and_refuses_empty_result(self):
        text='# Comment\n0 2 6 100 2047 2 AA\n0 2 6 100 1023 2 BB\n'
        self.assertEqual(moduli.filter_moduli(text,2048),'# Comment\n0 2 6 100 2047 2 AA\n')
        with self.assertRaises(ValueError): moduli.filter_moduli(text,4096)

    def test_watchdog_restores_files_and_marks_transaction_expired(self):
        with tempfile.TemporaryDirectory() as temp:
            state=Path(temp)/'state';state.mkdir()
            target=Path(temp)/'config';target.write_text('new')
            (state/'state.json').write_text(json.dumps({'kind':'client','files':{str(target):{
                'content':'old','mode':0o600,'uid':os.getuid(),'gid':os.getgid()}},'firewall':{}}))
            (state/'pending').touch()
            result=subprocess.run(['python3','-c',transaction.WATCHDOG,str(state)],capture_output=True,text=True)
            self.assertEqual(result.returncode,0,result.stderr)
            self.assertEqual(target.read_text(),'old')
            self.assertTrue((state/'rolled-back').exists())
            self.assertFalse((state/'pending').exists())

    def test_commit_rejects_expired_or_foreign_token(self):
        with tempfile.TemporaryDirectory() as temp, patch.object(transaction,'state_root',return_value=Path(temp)):
            (Path(temp)/'state.json').write_text(json.dumps({'token':'a'*32}))
            with self.assertRaises(ValueError): transaction.commit('server','a'*32)
            (Path(temp)/'pending').touch()
            with self.assertRaises(ValueError): transaction.commit('server','b'*32)

    def test_commit_persists_only_selected_family_after_runtime_validation(self):
        with tempfile.TemporaryDirectory() as temp:
            state=Path(temp)/'state';state.mkdir()
            output=Path(temp)/'rules.v4';output.write_text('old persistence')
            info={'token':'a'*32,'kind':'firewall','files':{},'firewall':{'iptables':SNAPSHOT},
                  'desired_files':{},'desired_firewall':{'iptables':SNAPSHOT},'persistent':True}
            (state/'state.json').write_text(json.dumps(info));(state/'pending').touch()
            calls=[]
            def command(argv,data=None):
                calls.append(argv)
                return SNAPSHOT if argv[0]=='iptables-save' else ''
            with patch.object(transaction,'state_root',return_value=state), \
                 patch.object(transaction,'persistence_path',return_value=output), \
                 patch.object(transaction,'run',side_effect=command), \
                 patch.object(transaction.os,'chown'):
                transaction.commit('firewall','a'*32)
            self.assertEqual(output.read_text(),SNAPSHOT)
            self.assertFalse(state.exists())
            self.assertFalse(any('ip6tables' in argv[0] for argv in calls))
            self.assertIn(['iptables-restore','--test','--wait','10'],calls)

    def test_persistence_failure_keeps_rollback_armed_and_original_journaled(self):
        with tempfile.TemporaryDirectory() as temp:
            state=Path(temp)/'state';state.mkdir()
            output=Path(temp)/'rules.v4';output.write_text('old persistence')
            info={'token':'a'*32,'kind':'firewall','files':{},'firewall':{'iptables':SNAPSHOT},
                  'desired_files':{},'desired_firewall':{'iptables':SNAPSHOT},'persistent':True}
            (state/'state.json').write_text(json.dumps(info));(state/'pending').touch()
            real_atomic=transaction.atomic
            def write(path,data,metadata=None):
                if Path(path)==output:
                    raise OSError('Simulated full filesystem')
                real_atomic(path,data,metadata)
            with patch.object(transaction,'state_root',return_value=state), \
                 patch.object(transaction,'persistence_path',return_value=output), \
                 patch.object(transaction,'run',side_effect=lambda argv,data=None: SNAPSHOT if argv[0]=='iptables-save' else ''), \
                 patch.object(transaction,'atomic',side_effect=write), \
                 patch.object(transaction.os,'chown'):
                with self.assertRaises(OSError): transaction.commit('firewall','a'*32)
            self.assertEqual(output.read_text(),'old persistence')
            self.assertTrue((state/'pending').exists())
            journal=json.loads((state/'state.json').read_text())
            self.assertEqual(journal['files'][str(output)]['content'],'old persistence')

    def test_second_family_apply_failure_invokes_rollback_without_persistence(self):
        with tempfile.TemporaryDirectory() as temp:
            state=Path(temp)/'state'
            calls=[]
            def command(argv,data=None):
                calls.append(argv)
                if argv[0].endswith('-save'): return SNAPSHOT
                if argv[0]=='ip6tables-restore': raise RuntimeError('Simulated second-family failure')
                return ''
            proposed=transaction.merge_rules(SNAPSHOT,'',{'INPUT':{'enabled':True,'value':'DROP'}})
            with patch.object(transaction,'state_root',return_value=state), \
                 patch.object(transaction,'run',side_effect=command), \
                 patch.object(transaction.subprocess,'run') as watchdog:
                with self.assertRaises(RuntimeError):
                    transaction.apply_transaction('firewall',{}, {},
                        {'iptables':SNAPSHOT,'ip6tables':SNAPSHOT},
                        {'iptables':proposed,'ip6tables':proposed},True,180)
            watchdog.assert_called_once()
            self.assertIn('rollback.py',watchdog.call_args.args[0][1])
            self.assertFalse(any(argv==['iptables-save'] for argv in calls))

